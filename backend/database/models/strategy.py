from __future__ import annotations

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import Boolean, ForeignKey, Integer, String, func
from sqlalchemy import Enum as SqlEnum
from sqlalchemy.orm import Mapped, mapped_column, relationship

from database.base import Base
from database.models.enums import TyreCompound
from database.models.mixins import TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from database.models.session import RaceSession


class StrategyPlan(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """A pit/tyre recommendation generated by the strategy engine.

    A session accumulates many of these as the race evolves; `is_active`
    marks the current one so the API and dashboard only need one query
    to find "what should the driver do right now".
    """

    __tablename__ = "strategy_plans"

    session_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("sessions.id", ondelete="CASCADE"), index=True, nullable=False
    )
    recommended_pit_lap: Mapped[int | None] = mapped_column(Integer, nullable=True)
    recommended_compound: Mapped[TyreCompound | None] = mapped_column(
        SqlEnum(TyreCompound, native_enum=False, length=20, values_callable=lambda e: [m.value for m in e]),
        nullable=True,
    )
    reason: Mapped[str | None] = mapped_column(String(500), nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    generated_at: Mapped[datetime] = mapped_column(server_default=func.now(), nullable=False)

    session: Mapped[RaceSession] = relationship(back_populates="strategy_plans")

    def __repr__(self) -> str:  # pragma: no cover - debug helper
        return f"StrategyPlan(session_id={self.session_id!s}, pit_lap={self.recommended_pit_lap})"
